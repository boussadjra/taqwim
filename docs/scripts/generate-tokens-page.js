/**
 * Regenerates the design-token reference from `@taqwim/themes`.
 *
 * The same reason the Tailwind preset is generated: a hand-maintained copy of
 * the token table drifts the first time a token is added. Runs before the docs
 * build.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseTokens } from '../../packages/themes/scripts/tokens.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const variables = join(root, '..', 'packages', 'themes', 'src', 'variables.css')
const target = join(root, 'src', 'content', 'docs', 'reference', 'tokens.md')

const tokens = parseTokens(readFileSync(variables, 'utf8'))
const rows = Object.entries(tokens)
  .map(([name, value]) => `| \`--hijri-calendar-${name}\` | \`${value}\` |`)
  .join('\n')

writeFileSync(
  target,
  `---
title: Design tokens
description: Every custom property a Taqwim theme can set, with its default.
---

{/* Generated by docs/scripts/generate-tokens-page.js — do not edit. */}

The complete token contract. \`core.css\` consumes only these, every bundled theme
sets only these, and the Tailwind preset is generated from them — so this table
is the whole surface a custom theme has to work with.

Names keep the \`--hijri-calendar-\` prefix from the pre-1.0 stylesheets, so
overrides written against those still apply.

| Token | Default |
| --- | --- |
${rows}

## Responsive and preference overrides

\`variables.css\` also adjusts a subset of these:

- under \`max-width: 640px\`, cells and navigation buttons grow — small touch
  targets are wrong on phones
- under \`prefers-contrast: more\`, borders and text go to full black on white and
  the focus ring thickens
- under \`prefers-reduced-motion: reduce\`, all three transitions become \`none\`
- \`[data-taqwim-size='compact']\` and \`[data-taqwim-size='large']\` change metrics
  only, so they compose with any theme
`,
)

console.warn(`docs: ${Object.keys(tokens).length} tokens → reference/tokens.md`)
